/* runtime.h — runtime construction of presentations, diagrams and identity
 * actions as ordinary core terms (§§83–84).
 *
 * Every construction here is an ordinary typed value: a Maps record, a
 * presentation, a Diagram value, or the generic action term. Nothing is
 * registered, published or dispatched on by the evaluator; a program can
 * compute any of these, pass it on, project its fields and apply them. Each
 * construction is one fixed template per universe-level tuple, built once
 * over keyed formal variables and instantiated by simultaneous substitution
 * (reindex); the host declaration compiler is an adapter that exports its
 * source diagrams through the same constructors (rt_diagram_export).
 *
 * Types (all levels exact, never silently raised):
 *   Maps_{a,b}(X,Z)   = Σ(c:X→Z).Σ(d:Z→X).(Π x. d(c x) = x) × (Π z. c(d z) = z)   : U_max(a,b)
 *   Pres_{a,b}(Z)     = Σ(X:U_a).Maps_{a,b}(X,Z)                                  : U_max(a+1,b)
 *   Diagram_{b,r}(B)  = Σ(C:B).Σ(R:B→U_r).Π(y:B).Maps_{r,b}(R y, Path_B(C,y))     : U_max(b,r+1)
 * Field order of a Maps value is (c,(d,(h,k))).
 */
#ifndef CUBICAL_RUNTIME_H
#define CUBICAL_RUNTIME_H

#include "compiler.h"

/* ---- §83.1 maps and presentations ---- */
RefId rt_maps_type(uint64_t a, uint64_t b, RefId X, RefId Z);
RefId rt_maps_id(uint64_t a, RefId X);                                                   /* (id, id, λx.refl, λx.refl) */
RefId rt_maps_compose(uint64_t a, uint64_t b, uint64_t c, RefId X, RefId Y, RefId Z, RefId E, RefId F);   /* E : Maps(X,Y), F : Maps(Y,Z) ↦ Maps(X,Z) */
RefId rt_maps_inverse(uint64_t a, uint64_t b, RefId X, RefId Z, RefId E);               /* Maps(Z,X) */
RefId rt_pres_type(uint64_t a, uint64_t b, RefId Z);
RefId rt_pres_const(uint64_t a, RefId Z);                                                /* (Z, id maps) : Pres_{a,a}(Z) */
/* projections of a Maps value / a presentation / a diagram value */
RefId rt_maps_c(RefId m); RefId rt_maps_d(RefId m); RefId rt_maps_h(RefId m); RefId rt_maps_k(RefId m);
RefId rt_pres_X(RefId P); RefId rt_pres_maps(RefId P);

/* ---- §83.2 the dependent singleton ---- */
/* A : U_a, t : A, D : (x:A) → Path_A(t,x) → U_r.
 * S_D = Σ(x:A).Σ(e:t=x).D x e (level max(a,r)); Z = D t refl(t).
 * rt_singleton_type is S_D; rt_singleton_maps is (c,d,h,k) : Maps_{max(a,r),r}(S_D, Z) with
 *   c = Down, d = λz.(t,refl,z), h = λw.⟨i⟩(e@i, ⟨k⟩e@(i∧k), fill(¬i)), k = λz.⟨i⟩fill_Z(¬i);
 * rt_singleton is the presentation (S_D, maps) : Pres_{max(a,r),r}(Z). */
RefId rt_singleton_type(uint64_t a, uint64_t r, RefId A, RefId t, RefId D);
RefId rt_singleton_maps(uint64_t a, uint64_t r, RefId A, RefId t, RefId D);
RefId rt_singleton(uint64_t a, uint64_t r, RefId A, RefId t, RefId D);

/* ---- §83.3 diagram values ---- */
RefId rt_diagram_type(uint64_t b, uint64_t r, RefId B);
RefId rt_diagram_zero(uint64_t b, RefId B, RefId C);                                     /* Diagram_{b,b}(B) */
/* A : U_a, t : A, Q : (x:A) → (t=x) → Diagram_{b,r}(B) ↦ Diagram_{b,max(a,r)}(B) with
 * C' = C_{Q t refl}, R'(y) = Σx.Σe.R_{Q x e}(y), maps' = singleton ∘ centre maps */
RefId rt_diagram_extend(uint64_t a, uint64_t b, uint64_t r, RefId A, RefId t, RefId Q, RefId B);
RefId rt_diagram_value(RefId d);                     /* C */
RefId rt_diagram_family(RefId d, RefId y);           /* R y */
RefId rt_diagram_maps(RefId d, RefId y);             /* Maps(R y, Path_B(C,y)) */

/* ---- §83.4 the generic identity action ---- */
/* L : Diagram_{b,rl}(B), R : Diagram_{b,rr}(B), p : Path_B(C_L, C_R), y : B;
 *   dir 0: arg : R_L y ↦ d_R(y)(p⁻¹ · c_L(y)(arg)) : R_R y
 *   dir 1: arg : R_R y ↦ d_L(y)(p · c_R(y)(arg))   : R_L y */
RefId rt_action(int dir, uint64_t b, uint64_t rl, uint64_t rr, RefId B, RefId L, RefId R, RefId p, RefId y, RefId arg);
/* the same action as one closed function λL.λR.λp.λy.λarg. … and its type */
RefId rt_action_fun(int dir, uint64_t b, uint64_t rl, uint64_t rr, RefId B, RefId *type);
/* the middle path-space maps of the action at y as a Maps value
 * Maps_{b,b}(Path_B(C_L,y), Path_B(C_R,y)) = (λq.p⁻¹·q, λs.p·s, h, k) with the
 * groupoid witnesses of §83.4 (rt_groupoid_*) */
RefId rt_action_middle(uint64_t b, RefId B, RefId CL, RefId CR, RefId p, RefId y);
/* the full action with both inverse witnesses: Maps(R_L y, R_R y) =
 * compose(collapse_L(y), compose(middle, expand_R(y))) */
RefId rt_action_maps(uint64_t b, uint64_t rl, uint64_t rr, RefId B, RefId L, RefId R, RefId p, RefId y);

/* ---- §83.4 groupoid laws by path induction (fixed templates) ----
 * J(P, d, b, p) = coe^i P(p@i, ⟨j⟩p@(i∧j)) d. Each law is generated by path
 * induction on its path arguments left to right; the base case uses the
 * finite word construction K(w) : w = refl. */
RefId rt_J(uint64_t l, uint64_t lp, RefId A, RefId a, RefId P, RefId d, RefId b, RefId p);   /* P : (b:A) → (a=b) → U_lp */
RefId rt_lunit(uint64_t l, RefId A, RefId a, RefId b, RefId q);                                /* refl·q = q */
RefId rt_rinv(uint64_t l, RefId A, RefId a, RefId b, RefId p);                                 /* p·p⁻¹ = refl */
RefId rt_linv(uint64_t l, RefId A, RefId a, RefId b, RefId p);                                 /* p⁻¹·p = refl */
RefId rt_assoc(uint64_t l, RefId A, RefId a, RefId b, RefId c, RefId d, RefId p, RefId q, RefId r);   /* (p·q)·r = p·(q·r) */
RefId rt_ap(uint64_t l, uint64_t m, RefId A, RefId Bt, RefId f, RefId x, RefId y, RefId p);    /* ⟨i⟩ f(p@i) */

/* ---- §84.1 export of host diagrams ---- */
/* the ordinary Diagram value of a checked source diagram (ordinary diagrams)
 * or the presentation of its terminal type (residual descriptions), built by
 * the right fold of rt_diagram_extend / rt_singleton ending in zero / the
 * constant presentation; memoized per diagram. *type receives its type. */
RefId rt_diagram_export(DiagramId d, RefId *type);
/* §84.2 reuse along a known identity: coe^i O(p@i) a */
RefId rt_reuse(uint64_t lb, uint64_t lo, RefId B, RefId O, RefId x, RefId y, RefId p, RefId a);

size_t rt_template_count(void);     /* fixed templates built so far */
void rt_free(void);

#endif
